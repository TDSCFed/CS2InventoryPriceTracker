using System.Text.Json;

namespace CS2InventoryPriceTracker.Services;

/// <summary>An item as the CS2 Game Coordinator describes it: only ids, no names.</summary>
public record GcItem(
    ulong Id,
    uint DefIndex,
    uint Quality,
    string? CustomName,
    int? PaintIndex,
    float? PaintWear,
    uint? StickerKit,
    uint? MusicId,
    uint? CharmId,
    uint? GraffitiTint,
    bool HasStatTrak,
    ulong? CasketId,
    int? CasketItemCount,
    int? PaintSeed = null,
    uint? KillCount = null,
    IReadOnlyList<uint>? Stickers = null);

/// <summary>What the app shows for a <see cref="GcItem"/>.</summary>
public record ResolvedItem(string MarketHashName, string Name, string? Type, string? RarityColor, string? IconPath, bool Marketable);

/// <summary>
/// Turns Game Coordinator item ids into names, using the table in Resources/Raw/items.json
/// (generated by tools/generate_item_data.py).
/// </summary>
public class ItemCatalog
{
    public const uint StorageUnitDefIndex = 1201;

    private const uint StickerDefIndex = 1209;
    private const uint SealedGraffitiDefIndex = 1348;
    private const uint GraffitiDefIndex = 1349;
    private const uint MusicKitDefIndex = 1314;
    private const uint CharmDefIndex = 1355;
    private const uint PatchDefIndex = 4609;

    private const uint QualityUnusual = 3;   // ★ knives and gloves
    private const uint QualityStatTrak = 9;
    private const uint QualitySouvenir = 12;

    private readonly SemaphoreSlim _loadLock = new(1, 1);
    private Tables? _tables;

    private sealed record Tables(
        Dictionary<string, string[]> Defs,
        Dictionary<string, string[]> Skins,
        Dictionary<string, string[]> Stickers,
        Dictionary<string, string[]> Patches,
        Dictionary<string, string[]> Graffiti,
        Dictionary<string, string[]> Music,
        Dictionary<string, string[]> Charms,
        uint ClientVersion);

    private async Task<Tables> GetTablesAsync()
    {
        if (_tables is not null)
            return _tables;

        await _loadLock.WaitAsync();
        try
        {
            if (_tables is null)
            {
                await using var stream = await FileSystem.OpenAppPackageFileAsync("items.json");
                var data = await JsonSerializer.DeserializeAsync<Dictionary<string, JsonElement>>(stream)
                           ?? throw new InvalidDataException("items.json is empty.");

                Dictionary<string, string[]> Read(string name) =>
                    data.TryGetValue(name, out var element)
                        ? element.Deserialize<Dictionary<string, string[]>>() ?? new()
                        : new();

                _tables = new Tables(
                    Read("defs"), Read("skins"), Read("stickers"), Read("patches"),
                    Read("graffiti"), Read("music"), Read("charms"),
                    data.TryGetValue("clientVersion", out var version) && version.TryGetUInt32(out var v) ? v : 0);
            }
            return _tables;
        }
        finally
        {
            _loadLock.Release();
        }
    }

    /// <summary>Name of a sticker (or patch) kit, e.g. "Sticker | Natus Vincere | Katowice 2014".</summary>
    public async Task<string?> StickerNameAsync(uint kit)
    {
        var t = await GetTablesAsync();
        return Find(t.Stickers, kit) is { } sticker ? sticker[0] : Find(t.Patches, kit)?[0];
    }

    /// <summary>CS2 client version from the game files when items.json was generated (0 if unknown).</summary>
    public async Task<uint> GetClientVersionAsync() => (await GetTablesAsync()).ClientVersion;

    public async Task<ResolvedItem> ResolveAsync(GcItem item)
    {
        var t = await GetTablesAsync();
        var def = item.DefIndex.ToString();
        t.Defs.TryGetValue(def, out var defRow);

        switch (item.DefIndex)
        {
            case StickerDefIndex when Find(t.Stickers, item.StickerKit) is { } sticker:
                return FromRow(sticker, sticker[0], "Sticker", true);

            case PatchDefIndex when Find(t.Patches, item.StickerKit) is { } patch:
                return FromRow(patch, patch[0], "Patch", true);

            case SealedGraffitiDefIndex or GraffitiDefIndex when item.StickerKit is { } kit:
            {
                var row = (item.GraffitiTint is { } tint ? Find(t.Graffiti, $"{kit}_{tint}") : null) ?? Find(t.Graffiti, kit.ToString());
                if (row is not null)
                {
                    // Opened graffiti cannot be sold.
                    var sealedItem = item.DefIndex == SealedGraffitiDefIndex;
                    var name = sealedItem ? row[0] : row[0].Replace("Sealed Graffiti", "Graffiti");
                    return FromRow(row, name, "Graffiti", sealedItem);
                }
                break;
            }

            case MusicKitDefIndex when Find(t.Music, item.MusicId) is { } music:
            {
                var name = item.Quality == QualityStatTrak ? "StatTrak™ " + music[0] : music[0];
                return FromRow(music, name, "Music Kit", true);
            }

            case CharmDefIndex when Find(t.Charms, item.CharmId) is { } charm:
                return FromRow(charm, charm[0], "Charm", true);
        }

        var kind = defRow is { Length: > 3 } ? defRow[3] : "";
        var isStar = kind is "k" or "g" || item.Quality == QualityUnusual;

        // Weapon skins, knives and gloves.
        if (kind is "w" or "k" or "g")
        {
            var paint = item.PaintIndex ?? 0;
            var skin = Find(t.Skins, $"{def}_{paint}");
            if (skin is not null)
            {
                var prefix = isStar ? "★ " : "";
                if (item.HasStatTrak || item.Quality == QualityStatTrak)
                    prefix += "StatTrak™ ";
                else if (item.Quality == QualitySouvenir)
                    prefix += "Souvenir ";

                var wear = paint > 0 && item.PaintWear is { } w ? $" ({WearName(w)})" : "";
                var name = prefix + skin[0] + wear;
                var type = kind switch { "k" => "Knife", "g" => "Gloves", _ => "Weapon" };
                return FromRow(skin, name, type, true);
            }

            if (defRow is not null)
                return FromRow(defRow, defRow[0], "Weapon", false); // Stock weapon without a skin.
        }

        if (defRow is not null)
            return FromRow(defRow, defRow[0], null, kind == "m");

        return new ResolvedItem($"Unknown item #{item.DefIndex}", $"Unknown item #{item.DefIndex}", null, null, null, false);
    }

    private static ResolvedItem FromRow(string[] row, string name, string? type, bool marketable)
        => new(name, name, type, row.Length > 1 && row[1].Length > 0 ? row[1] : null, row.Length > 2 && row[2].Length > 0 ? row[2] : null, marketable);

    private static string[]? Find(Dictionary<string, string[]> table, uint? id)
        => id is null ? null : Find(table, id.Value.ToString());

    private static string[]? Find(Dictionary<string, string[]> table, string key)
        => table.TryGetValue(key, out var row) && row.Length > 0 ? row : null;

    /// <summary>Wear names used in Steam Market item names.</summary>
    public static string WearName(float wear) => wear switch
    {
        < 0.07f => "Factory New",
        < 0.15f => "Minimal Wear",
        < 0.38f => "Field-Tested",
        < 0.45f => "Well-Worn",
        _ => "Battle-Scarred"
    };
}
